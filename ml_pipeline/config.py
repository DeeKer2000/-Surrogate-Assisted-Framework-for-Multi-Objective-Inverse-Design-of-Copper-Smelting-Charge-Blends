# 5. KV 缓存加速策略（重要）
# ===========================================================================
# TabPFN 的 fit_mode="fit_with_cache" 会把训练上下文的 K/V 预先算好，
# 之后每次预测都不用再编码整份上下文，多目标/多划分时快很多。
#
# 但它与默认路径（fit_preprocessors，步骤1 使用）**不是数值等价的**：
# 两条引擎路径的注意力归约顺序不同，同一划分下（3000 数据、seed 42、matte_Cu_pct）
#     fit_preprocessors  R² = 0.9998369968128022   ← 与已归档结果逐位一致
#     fit_with_cache     R² = 0.9998353989154523   ← 差 1.6e-06
# 对较难的目标差距更明显（slag_Cu_pct）：0.89015 vs 0.88995，第 4 位小数可见。
#
# 所以：
#   - 要进论文表格、且必须与步骤1 口径一致的步骤（3、6）默认**关闭**缓存；
#   - 只有 SHAP（步骤4、5）默认开启——它每个特征联盟都要预测一次，
#     不开缓存要慢十几倍，而特征重要性排序对这种 1e-4 量级的差异不敏感。
# 想加速可在命令行加 --fit-mode cache（会改变表格数值，请自行确认是否可接受）。

